"""Capture devices and the go2rtc configuration for TanchTV ports.

A port = a capture card (identified by its USB port path, e.g. "3-2", because identical cards share
vendor/product/serial) + the device plugged into it. Each port gets two go2rtc streams:
  p<id>     1080p H.264 + Opus/AAC captured by capture.sh <usb> {output}
  p<id>_sd  720p transcode of p<id> (phones / weak links)
Both are preloaded (always running) so viewers never wait for a cold start.
"""

import os
from pathlib import Path

SYS_V4L = Path("/sys/class/video4linux")
SYS_SOUND = Path("/sys/class/sound")


def _read(p: Path) -> str:
    try:
        return p.read_text().strip()
    except OSError:
        return ""


def list_capture_devices() -> list[dict]:
    """Video capture devices (one per USB device), with whether they have an audio input."""
    audio_by_usb = {}
    if SYS_SOUND.exists():
        for c in SYS_SOUND.glob("card*"):
            if (c / "device").exists():
                audio_by_usb[(c / "device").resolve().parent.name] = _read(c / "id")
    out, seen = [], set()
    if not SYS_V4L.exists():
        return out
    for v in sorted(SYS_V4L.glob("video*"), key=lambda p: int(p.name[5:] or 0)):
        if _read(v / "index") not in ("0", ""):
            continue
        usbdev = (v / "device").resolve().parent
        usb = usbdev.name
        if usb in seen or "-" not in usb:
            continue
        seen.add(usb)
        vid, pid = _read(usbdev / "idVendor"), _read(usbdev / "idProduct")
        name = _read(v / "name").split(":")[0].strip() or "Video device"
        product = _read(usbdev / "product")
        if "(" in product and ")" not in product:        # e.g. "UVC Camera (534d" (truncated by the device)
            product = product.split("(")[0].strip()
        if vid == "534d" and product.lower().startswith(("uvc camera", "usb video")) or not product:
            product = "HDMI capture (MS2109)" if vid == "534d" else name
        out.append({
            "usb": usb, "name": product or name, "vendor_product": f"{vid}:{pid}" if vid else "",
            "manufacturer": _read(usbdev / "manufacturer"), "audio": audio_by_usb.get(usb),
            "hdmi_capture": vid == "534d" or "capture" in (name + product).lower(),
        })
    return out


def _go2rtc_header() -> str:
    """go2rtc's API/RTSP stay on loopback (the only client is the TanchTV app, which does sign-in);
    WebRTC (8555 tcp+udp) listens on the interfaces in WEBRTC_INTERFACES (comma list; empty = all)."""
    ifaces = [i.strip() for i in os.environ.get("WEBRTC_INTERFACES", "").split(",") if i.strip()]
    lines = [
        "# Generated by TanchTV (Settings -> Ports). Edits here are overwritten when ports change.",
        "api:",
        '  listen: "127.0.0.1:1984"',
        "",
        "rtsp:",
        '  listen: "127.0.0.1:18554"',
        "",
        "webrtc:",
        '  listen: ":8555"',
        "  filters:",
    ]
    if ifaces:
        lines.append(f"    interfaces: [{', '.join(ifaces)}]")
    lines += ["    networks: [udp4, tcp4]", "", "log:", "  level: info", ""]
    return "\n".join(lines)


def _sd_transcode() -> str:
    """The 720p 'SD' stream is a go2rtc ffmpeg transcode of the HD one (GPU unless HWACCEL=none)."""
    hw = "" if os.environ.get("HWACCEL", "vaapi") == "none" else "#hardware=vaapi"
    return f"#video=h264#width=1280#height=720{hw}#audio=opus#audio=aac#raw=-b:v 2500k -maxrate 3M -bufsize 500k -g 60"


def stream_names(port_id: int) -> tuple[str, str]:
    return f"p{port_id}", f"p{port_id}_sd"


def build_go2rtc_yaml(ports: list[dict]) -> str:
    lines = [_go2rtc_header(), "streams:"]
    if not ports:
        lines.append("  {}")
    for p in ports:
        hd, sd = stream_names(p["id"])
        lines.append(f"  # port {p['id']}: {p['name']} (USB {p['usb']})")
        lines.append(f"  {hd}: exec:/config/capture.sh {p['usb']} {{output}}")
        lines.append(f"  {sd}: ffmpeg:{hd}{_sd_transcode()}")
    lines.append("")
    if ports:
        lines.append("# Always running, so the first viewer doesn't wait for capture + transcoder start-up.")
        lines.append("preload:")
        for p in ports:
            hd, sd = stream_names(p["id"])
            lines.append(f"  {hd}:")
            lines.append(f"  {sd}:")
    return "\n".join(lines) + "\n"
